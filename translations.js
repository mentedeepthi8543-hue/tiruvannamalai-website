/* =========================================================
   TRANSLATION FUNCTIONS
========================================================= */

let currentLanguage = "en";

const originalTextMap = new WeakMap();


function normalizeText(text) {
    return text.replace(/\s+/g, " ").trim();
}


function findOriginalEnglish(text) {
    const normalizedText = normalizeText(text);

    if (!normalizedText) {
        return "";
    }

    if (
        translations.te[normalizedText] ||
        translations.hi[normalizedText] ||
        translations.ta[normalizedText]
    ) {
        return normalizedText;
    }

    for (const language of ["te", "hi", "ta"]) {
        const languageTranslations = translations[language];

        for (const englishText in languageTranslations) {
            if (
                normalizeText(languageTranslations[englishText]) ===
                normalizedText
            ) {
                return englishText;
            }
        }
    }

    return normalizedText;
}


function translateTextNode(textNode, language) {
    const currentText = textNode.nodeValue;

    if (!currentText || !currentText.trim()) {
        return;
    }

    let originalEnglish = originalTextMap.get(textNode);

    const detectedEnglish = findOriginalEnglish(currentText);

    /*
       When script.js changes weather or status text,
       update the stored original English value.
    */
    if (
        !originalEnglish ||
        (
            currentLanguage !== "en" &&
            detectedEnglish === normalizeText(currentText)
        )
    ) {
        originalEnglish = detectedEnglish;
        originalTextMap.set(textNode, originalEnglish);
    }

    const leadingSpace = currentText.match(/^\s*/)?.[0] || "";
    const trailingSpace = currentText.match(/\s*$/)?.[0] || "";

    if (language === "en") {
        textNode.nodeValue =
            leadingSpace + originalEnglish + trailingSpace;

        return;
    }

    const translatedText =
        translations[language]?.[originalEnglish];

    if (translatedText) {
        textNode.nodeValue =
            leadingSpace + translatedText + trailingSpace;
    } else {
        textNode.nodeValue =
            leadingSpace + originalEnglish + trailingSpace;
    }
}


function translateElementAttributes(element, language) {
    const attributes = ["title", "placeholder", "aria-label"];

    attributes.forEach((attributeName) => {
        if (!element.hasAttribute(attributeName)) {
            return;
        }

        const originalAttributeName =
            `data-original-${attributeName}`;

        if (!element.hasAttribute(originalAttributeName)) {
            element.setAttribute(
                originalAttributeName,
                element.getAttribute(attributeName)
            );
        }

        const originalValue =
            element.getAttribute(originalAttributeName);

        if (language === "en") {
            element.setAttribute(attributeName, originalValue);
            return;
        }

        const translatedValue =
            translations[language]?.[originalValue];

        element.setAttribute(
            attributeName,
            translatedValue || originalValue
        );
    });
}


function translateNode(rootNode, language) {
    if (!rootNode) {
        return;
    }

    if (rootNode.nodeType === Node.TEXT_NODE) {
        translateTextNode(rootNode, language);
        return;
    }

    if (rootNode.nodeType !== Node.ELEMENT_NODE) {
        return;
    }

    const element = rootNode;

    /*
       Do not translate JavaScript, CSS, input values
       or the language names inside the selector.
    */
    if (
        ["SCRIPT", "STYLE", "NOSCRIPT"].includes(element.tagName)
    ) {
        return;
    }

    translateElementAttributes(element, language);

    element.childNodes.forEach((childNode) => {
        translateNode(childNode, language);
    });
}


function translateWholeWebsite(language) {
    currentLanguage = language;

    document.documentElement.lang = language;

    translateNode(document.body, language);

    localStorage.setItem(
        "selectedLanguage",
        language
    );

    /*
       Let script.js access the selected language.
    */
    window.currentWebsiteLanguage = language;

    document.dispatchEvent(
        new CustomEvent("websiteLanguageChanged", {
            detail: {
                language: language
            }
        })
    );
}


function changeLanguage(language) {
    const allowedLanguages = ["en", "te", "hi", "ta"];

    const validLanguage =
        allowedLanguages.includes(language)
            ? language
            : "en";

    translateWholeWebsite(validLanguage);
}


/* Make function available to other JavaScript files */
window.changeLanguage = changeLanguage;


/* =========================================================
   PAGE INITIALIZATION
========================================================= */

document.addEventListener("DOMContentLoaded", function () {
    const languageSelector =
        document.getElementById("languageSelector");

    if (!languageSelector) {
        console.error(
            "Language selector not found. Add id='languageSelector'."
        );

        return;
    }

    const savedLanguage =
        localStorage.getItem("selectedLanguage") || "en";

    languageSelector.value = savedLanguage;

    changeLanguage(savedLanguage);

    languageSelector.addEventListener(
        "change",
        function () {
            changeLanguage(this.value);
        }
    );


    /*
       This watches text generated later by script.js,
       such as weather, temple status and recommendations.
    */

    let translationTimer;

    const observer = new MutationObserver(function (mutations) {
        let requiresTranslation = false;

        mutations.forEach((mutation) => {
            if (
                mutation.type === "childList" ||
                mutation.type === "characterData"
            ) {
                requiresTranslation = true;
            }
        });

        if (!requiresTranslation) {
            return;
        }

        clearTimeout(translationTimer);

        translationTimer = setTimeout(function () {
            translateNode(
                document.body,
                currentLanguage
            );
        }, 80);
    });

    observer.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true
    });
});